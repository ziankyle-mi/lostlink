import { z } from "zod";

/** Field validation for every step. Keep messages short and plain. */

export const emailSchema = z
  .string()
  .trim()
  .toLowerCase()
  .min(1, "Email is required.")
  .max(254, "Email is too long.")
  .email("Enter a valid email address.");

export const passwordSchema = z
  .string()
  .min(8, "Use at least 8 characters.")
  .max(72, "Password is too long.");

export const nextPathSchema = z
  .string()
  .trim()
  .max(200)
  .optional()
  .default("/");

export const loginSchema = z.object({
  email: emailSchema,
  password: z.string().min(1, "Password is required.").max(72, "Password is too long."),
  remember: z.coerce.boolean().optional().default(false),
  next: nextPathSchema,
});

export const STANDARD_YEAR_LEVELS = ["1st Year", "2nd Year", "3rd Year", "4th Year"] as const;
export const DVM_YEAR_LEVELS = [
  "1st Year",
  "2nd Year",
  "3rd Year",
  "4th Year",
  "5th Year",
  "6th Year",
] as const;
export const ALL_YEAR_LEVELS = DVM_YEAR_LEVELS;
export const YEAR_LEVELS = ALL_YEAR_LEVELS;

export const STUDENT_ID_REGEX = /^[0-9]{4}-00-[0-9]{6}$/;

export const registerSchema = z
  .object({
    name: z
      .string()
      .trim()
      .min(2, "Enter your full name.")
      .max(80, "Name is too long."),
    email: emailSchema,
    password: passwordSchema,
    agree: z.coerce.boolean().optional().default(false),
    // "admin" is deliberately absent: privilege is granted only by the
    // Security Office, never by the registration form.
    role: z.enum(["student", "faculty"]).optional().default("student"),
    program: z
      .string()
      .trim()
      .min(1, "Select your degree program or department affiliation."),
    studentId: z.string().trim().optional(),
    yearLevel: z.string().trim().optional(),
  })
  .superRefine((data, ctx) => {
    // Student ID and Year Level are strictly required for students, but not applicable for faculty or admin
    if (data.role === "student" || !data.role) {
      if (!data.studentId || data.studentId.trim().length === 0) {
        ctx.addIssue({
          code: z.ZodIssueCode.custom,
          message: "Enter your Student ID (format: YYYY-00-XXXXXX, e.g. 2024-00-000920).",
          path: ["studentId"],
        });
      } else if (!STUDENT_ID_REGEX.test(data.studentId.trim())) {
        ctx.addIssue({
          code: z.ZodIssueCode.custom,
          message: "Student ID must follow format YYYY-00-XXXXXX (e.g. 2024-00-000920).",
          path: ["studentId"],
        });
      }
      if (!data.yearLevel || data.yearLevel.trim().length === 0) {
        ctx.addIssue({
          code: z.ZodIssueCode.custom,
          message: "Select your current year level.",
          path: ["yearLevel"],
        });
      } else {
        const allowed = data.program === "DVM" ? DVM_YEAR_LEVELS : STANDARD_YEAR_LEVELS;
        if (!allowed.includes(data.yearLevel as any)) {
          ctx.addIssue({
            code: z.ZodIssueCode.custom,
            message:
              data.program === "DVM"
                ? "DVM year level must be between 1st Year and 6th Year."
                : `${data.program || "This"} is a 4-year degree program (1st to 4th Year).`,
            path: ["yearLevel"],
          });
        }
      }
    }
  });

export const forgotPasswordSchema = z.object({
  email: emailSchema,
});

export const resetPasswordSchema = z
  .object({
    password: passwordSchema,
    confirm: z.string().min(1, "Confirm your password."),
  })
  .refine((values) => values.password === values.confirm, {
    message: "Passwords must match.",
    path: ["confirm"],
  });

export const emptySchema = z.object({}).passthrough();

/**
 * Storage object paths are filenames generated by the upload endpoint
 * (`<uuid>.<ext>`). Anything else is rejected so a client cannot attach an
 * arbitrary path or another user's object to a report.
 */
export const PHOTO_PATH_REGEX =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(jpe?g|png|webp)$/i;

export const reportSchema = z.object({
  type: z
    .string()
    .refine((value) => value === "lost" || value === "found", {
      message: "Type must be 'lost' or 'found'.",
    }),
  name: z
    .string()
    .trim()
    .min(2, "Item name must be at least 2 characters.")
    .max(120, "Item name is too long."),
  category: z.string().trim().min(1, "Category is required.").max(80, "Category is too long."),
  location: z.string().trim().min(1, "Location is required.").max(120, "Location is too long."),
  description: z
    .string()
    .trim()
    .min(
      25,
      "Please provide a more complete description (at least 25 characters) detailing color, brand, condition, or unique marks to help identify the item.",
    )
    .max(2000, "Description is too long."),
  eventDate: z
    .string()
    .trim()
    .regex(/^\d{4}-\d{2}-\d{2}$/, "Enter a valid date.")
    .optional(),
  photos: z.array(z.string()).max(6).optional(),
  photoUrls: z.array(z.string()).max(6).optional(),
  photoPaths: z.array(z.string()).max(6).optional(),
  turnstileToken: z.string().optional(),
});

/** Office decision on an item that has been unclaimed past the custody window. */
export const custodyDecisionSchema = z.object({
  itemId: z.string().uuid("That item reference is not valid."),
  decision: z.enum(["extend_custody", "mark_donation"]),
});

/** Local dev only: auto-login test button signs in this address. */
export const devLoginSchema = z.object({
  email: emailSchema.optional().default("firstname.lastname@dlsau.edu.ph"),
  next: nextPathSchema,
});

export type LoginInput = z.infer<typeof loginSchema>;
export type RegisterInput = z.infer<typeof registerSchema>;